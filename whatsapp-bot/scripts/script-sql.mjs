/**
 * Print migration 120: the bot's built-in admission questions as the Flow
 * Builder's "Admission script" row (src/flows/seed.mjs).
 *
 *   node scripts/script-sql.mjs > ../supabase/migrations/120_whatsapp_admission_script.sql
 */

import { admissionScript } from '../src/flows/seed.mjs'

const json = JSON.stringify(admissionScript())
if (json.includes('$seed$')) throw new Error('seed text contains the SQL quote tag')

process.stdout.write(`-- The WhatsApp bot's admission questions, editable in the Flow Builder.
--
-- Until now the 10th/12th and college questions lived only in the bot's code.
-- This adds them as one flow of kind 'script' — the "Admission script" — so
-- admin can reword questions and options, add steps and branches, from the
-- CRM. The bot still reads typed answers, fills several answers from one
-- message and scores the lead the same way; switching the script off (or a
-- script it cannot run) puts the built-in questions back.
--
-- Generated by whatsapp-bot/scripts/script-sql.mjs from src/flows/seed.mjs.

ALTER TABLE wa_flows ADD COLUMN IF NOT EXISTS kind text NOT NULL DEFAULT 'custom';

DO $$ BEGIN
  ALTER TABLE wa_flows ADD CONSTRAINT wa_flows_kind_check CHECK (kind IN ('custom', 'script'));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

-- One admission script.
CREATE UNIQUE INDEX IF NOT EXISTS wa_flows_one_script ON wa_flows (kind) WHERE kind = 'script';

INSERT INTO wa_flows (name, kind, triggers, match_mode, on_first_message, root, is_active)
SELECT 'Admission script', 'script', '{}', 'exact', false, $seed$${json}$seed$::jsonb, true
WHERE NOT EXISTS (SELECT 1 FROM wa_flows WHERE kind = 'script');
`)
